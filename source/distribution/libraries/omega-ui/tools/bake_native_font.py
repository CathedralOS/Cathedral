"""Bake the bundled fonts into bounded grayscale glyph data for native hosts.

Run with Pillow installed only when regenerating the checked-in atlas. Ordinary
library/guest builds consume the generated Omega source without a Python font
runtime. Each glyph carries metrics, row offsets, then coverage/run-length pairs.
"""
import hashlib
import json
from pathlib import Path
from PIL import Image, ImageDraw, ImageFont, __version__

ROOT = Path(__file__).resolve().parents[1]


def glyph(font, character, height, baseline):
    advance = round(font.getlength(character) / 4)
    left, _, right, _ = font.getbbox(character, anchor='ls')
    origin = min(left // 4, 0)
    width = max((right + 3) // 4 - origin, advance, 1)
    image = Image.new('L', (width * 4, height * 4))
    ImageDraw.Draw(image).text((-origin * 4, baseline * 4), character, font=font, fill=255, anchor='ls')
    image = image.resize((width, height), Image.Resampling.LANCZOS)
    values = [(value * 15 + 127) // 255 for value in image.tobytes()]
    occupied = [(i % width, i // width) for i, value in enumerate(values) if value]
    if not occupied:
        return ''.join(chr(64 + value) for value in (advance, 0, 0, 0, 0))
    x0, x1 = min(x for x, _ in occupied), max(x for x, _ in occupied) + 1
    y0, y1 = min(y for _, y in occupied), max(y for _, y in occupied) + 1
    rows, payload = [], ''
    for y in range(y0, y1):
        rows.append(len(payload))
        expected = values[y * width + x0:y * width + x1]
        at = 0
        while at < len(expected):
            end = at + 1
            while end < len(expected) and expected[end] == expected[at] and end - at < 26:
                end += 1
            payload += chr(64 + end - at) + chr(97 + expected[at])
            at = end
        decoded = []
        for at in range(rows[-1], len(payload), 2):
            decoded.extend([ord(payload[at + 1]) - 97] * (ord(payload[at]) - 64))
        assert decoded == expected
    header = ''.join(chr(64 + value) for value in (advance, origin + x0, y0, x1 - x0, y1 - y0))
    offsets = ''.join(chr(33 + offset // 90) + chr(33 + offset % 90) for offset in rows)
    assert all(32 <= ord(value) <= 126 for value in header + offsets + payload)
    return header + offsets + payload


def main():
    output = ['// Generated by tools/bake_native_font.py; bundled font notice remains in assets/fonts/inter/.',
              'use omega_ui::types;', 'use font;',
              'public data NativeFontAtlas {}',
              'data GlyphSpan { begin: u64; end: u64; }',
              'public machine NativeFontAtlas::advance(character: i32, large: bool) -> i32 {',
              '    transition large { true -> (large_advance(character)) _ -> (body_advance(character)) }', '}',
              'public machine NativeFontAtlas::paint(character: i32, large: bool, pixels: &mut [i32; 4096], row: i32, x: i32, local_y: i32, color: i32, clip_left: i32, clip_right: i32) {',
              '''    transition large { true -> large_row(character, pixels, row, x, local_y, color, clip_left, clip_right) _ -> body_row(character, pixels, row, x, local_y, color, clip_left, clip_right) }
    state large_row(character: i32, pixels: &mut [i32; 4096], row: i32, x: i32, local_y: i32, color: i32, clip_left: i32, clip_right: i32) {
        large_paint(character, pixels, row, x, local_y, color, clip_left, clip_right);
    }
    state body_row(character: i32, pixels: &mut [i32; 4096], row: i32, x: i32, local_y: i32, color: i32, clip_left: i32, clip_right: i32) {
        body_paint(character, pixels, row, x, local_y, color, clip_left, clip_right);
    }''', '}']
    records = []
    for name, filename, size, height, baseline in (
        ('body', 'Inter-Regular.ttf', 16, 20, 16),
        ('large', 'Inter-SemiBold.ttf', 24, 32, 25),
    ):
        path = ROOT / 'assets/fonts/inter' / filename
        font = ImageFont.truetype(str(path), size * 4)
        data = {character: glyph(font, chr(character), height, baseline) for character in range(32, 127)}
        atlas = ''.join(data.values())
        starts = [0]
        for encoded in data.values():
            starts.append(starts[-1] + len(encoded))
        offsets = ''.join(chr(33 + offset // 8100) + chr(33 + offset // 90 % 90) + chr(33 + offset % 90) for offset in starts)
        advances = ''.join(encoded[0] for encoded in data.values())
        output.extend([f'machine {name}_advance(character: i32) -> i32 {{',
                       f'    let advances: &[u8] = {json.dumps(advances)};',
                       '    advance(character, advances)', '}',
                       f'machine {name}_paint(character: i32, pixels: &mut [i32; 4096], row: i32, x: i32, local_y: i32, color: i32, clip_left: i32, clip_right: i32) {{',
                       f'    let atlas: &[u8] = {json.dumps(atlas)};',
                       f'    let offsets: &[u8] = {json.dumps(offsets)};',
                       '    paint(character, offsets, atlas, pixels, row, x, local_y, color, clip_left, clip_right);', '}'])
        records.append({'font': path.relative_to(ROOT).as_posix(), 'sha256': hashlib.sha256(path.read_bytes()).hexdigest(),
                        'size': size, 'line_height': height, 'baseline': baseline, 'glyphs': 95,
                        'encoded_bytes': sum(map(len, data.values()))})
    output.extend(['''machine advance(character: i32, advances: &[u8]) -> i32 {
    let index: i32 = select_i32(character >= 32 && character <= 126, sub_i32(character, 32), 31);
    transition index >= 0 && index < 95 && (index as u64) < advances.len {
        true -> (sub_i32(advances[index as u64] as i32, 64))
        _ -> (0)
    }
}
machine paint(character: i32, offsets: &[u8], atlas: &[u8], pixels: &mut [i32; 4096], row: i32, x: i32, local_y: i32, color: i32, clip_left: i32, clip_right: i32) {
    let span: GlyphSpan = lookup(character, offsets);
    transition span.begin <= span.end && span.end <= atlas.len {
        true -> draw(atlas, pixels, row, x, local_y, color, clip_left, clip_right, span)
        _ -> done()
    }
    state draw(atlas: &[u8], pixels: &mut [i32; 4096], row: i32, x: i32, local_y: i32, color: i32, clip_left: i32, clip_right: i32, span: GlyphSpan)
    requires span.begin <= span.end && span.end <= atlas.len {
        NativeUiFont::glyph_row(pixels, row, &atlas[span.begin..span.end], x, local_y, color, clip_left, clip_right);
    }
    state done() {}
}
machine lookup(character: i32, offsets: &[u8]) -> GlyphSpan {
    let index: i32 = select_i32(character >= 32 && character <= 126, sub_i32(character, 32), 31);
    transition index >= 0 && index < 95 { true -> position(index, offsets) _ -> (GlyphSpan { begin: 0u64, end: 0u64 }) }
    state position(index: i32, offsets: &[u8]) -> GlyphSpan requires index >= 0 && index < 95 {
        let at: u64 = (index as u64) * 3u64;
        transition at + 5u64 < offsets.len { true -> bounds(offsets, at) _ -> (GlyphSpan { begin: 0u64, end: 0u64 }) }
    }
    state bounds(offsets: &[u8], at: u64) -> GlyphSpan requires at <= 282u64 && at + 5u64 < offsets.len {
        let begin: i32 = add_i32(add_i32(mul_i32(sub_i32(offsets[at] as i32, 33), 8100), mul_i32(sub_i32(offsets[at + 1u64] as i32, 33), 90)), sub_i32(offsets[at + 2u64] as i32, 33));
        let end: i32 = add_i32(add_i32(mul_i32(sub_i32(offsets[at + 3u64] as i32, 33), 8100), mul_i32(sub_i32(offsets[at + 4u64] as i32, 33), 90)), sub_i32(offsets[at + 5u64] as i32, 33));
        transition begin >= 0 && begin <= 65536 && end >= 0 && end <= 65536 && end >= begin {
            true -> (GlyphSpan { begin: begin as u64, end: end as u64 })
            _ -> (GlyphSpan { begin: 0u64, end: 0u64 })
        }
    }
}'''])
    (ROOT / 'platform/native/font_atlas.omg').write_text('\n'.join(output) + '\n')
    (ROOT / 'platform/native/font_atlas.json').write_text(json.dumps({'pillow': __version__, 'coverage_levels': 16, 'fonts': records}, indent=2) + '\n')
    print(records)


if __name__ == '__main__':
    main()
